CREATE EXTENSION IF NOT EXISTS vector;

-- 1. departments
CREATE TABLE IF NOT EXISTS public.departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR,
    name VARCHAR,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 2. users
CREATE TABLE IF NOT EXISTS public.users (
    id UUID PRIMARY KEY,
    user_code VARCHAR,
    full_name VARCHAR,
    email VARCHAR,
    password_hash VARCHAR,
    role VARCHAR,
    user_type VARCHAR,
    department_id BIGINT REFERENCES public.departments(id),
    enrollment_year INTEGER,
    status VARCHAR,
    card_expiry TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 3. user_profiles
CREATE TABLE IF NOT EXISTS public.user_profiles (
    user_id UUID PRIMARY KEY REFERENCES public.users(id),
    profile_embedding vector,
    top_topics JSONB,
    preferred_format VARCHAR,
    preferred_categories TEXT[],
    personalization_enabled BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 4. documents
CREATE TABLE IF NOT EXISTS public.documents (
    id UUID PRIMARY KEY,
    title VARCHAR,
    isbn VARCHAR,
    publisher VARCHAR,
    publication_year INTEGER,
    language VARCHAR,
    doc_type VARCHAR,
    classification_number VARCHAR,
    abstract TEXT,
    metadata JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ
);

-- 5. authors
CREATE TABLE IF NOT EXISTS public.authors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 6. document_authors
CREATE TABLE IF NOT EXISTS public.document_authors (
    document_id UUID NOT NULL REFERENCES public.documents(id),
    author_id BIGINT NOT NULL REFERENCES public.authors(id),
    author_order INTEGER,
    PRIMARY KEY (document_id, author_id)
);

-- 7. document_departments
CREATE TABLE IF NOT EXISTS public.document_departments (
    document_id UUID NOT NULL REFERENCES public.documents(id),
    department_id BIGINT NOT NULL REFERENCES public.departments(id),
    course_year INTEGER,
    PRIMARY KEY (document_id, department_id)
);

-- 8. physical_copies
CREATE TABLE IF NOT EXISTS public.physical_copies (
    id UUID PRIMARY KEY,
    document_id UUID NOT NULL REFERENCES public.documents(id),
    barcode VARCHAR,
    call_number VARCHAR,
    shelf_location VARCHAR,
    status VARCHAR,
    accession_date TIMESTAMPTZ,
    last_inventory_date TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ
);

-- 9. digital_copies
CREATE TABLE IF NOT EXISTS public.digital_copies (
    id UUID PRIMARY KEY,
    document_id UUID NOT NULL REFERENCES public.documents(id),
    version VARCHAR,
    is_current BOOLEAN,
    processing_status VARCHAR,
    file_path VARCHAR,
    file_hash VARCHAR,
    file_size BIGINT,
    page_count INTEGER,
    extraction_quality DOUBLE PRECISION,
    uploaded_by UUID REFERENCES public.users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 10. favorites
CREATE TABLE IF NOT EXISTS public.favorites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.users(id),
    document_id UUID NOT NULL REFERENCES public.documents(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 11. reviews
CREATE TABLE IF NOT EXISTS public.reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.users(id),
    document_id UUID NOT NULL REFERENCES public.documents(id),
    rating INTEGER CHECK (rating >= 1 AND rating <= 5),
    comment TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 12. loan_policies
CREATE TABLE IF NOT EXISTS public.loan_policies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_type VARCHAR,
    doc_type VARCHAR,
    loan_days INTEGER,
    max_loans INTEGER,
    max_renewals INTEGER,
    hold_expiry_days INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 13. circulation
CREATE TABLE IF NOT EXISTS public.circulation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.users(id),
    physical_copy_id UUID NOT NULL REFERENCES public.physical_copies(id),
    issued_by UUID REFERENCES public.users(id),
    borrow_date TIMESTAMPTZ,
    due_date TIMESTAMPTZ,
    return_date TIMESTAMPTZ,
    borrow_note TEXT,
    return_note TEXT,
    renewals_count INTEGER NOT NULL DEFAULT 0
);

-- 14. penalty_types
CREATE TABLE IF NOT EXISTS public.penalty_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR,
    name VARCHAR,
    unit_name VARCHAR,
    unit_price BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 15. circulation_fines
CREATE TABLE IF NOT EXISTS public.circulation_fines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    circulation_id BIGINT NOT NULL REFERENCES public.circulation(id),
    penalty_type_id BIGINT NOT NULL REFERENCES public.penalty_types(id),
    quantity INTEGER,
    fine_amount BIGINT,
    status VARCHAR,
    note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 16. holds_queue
CREATE TABLE IF NOT EXISTS public.holds_queue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.users(id),
    document_id UUID NOT NULL REFERENCES public.documents(id),
    physical_copy_id UUID REFERENCES public.physical_copies(id),
    queue_position INTEGER,
    request_date TIMESTAMPTZ,
    ready_date TIMESTAMPTZ,
    pickup_deadline TIMESTAMPTZ,
    status VARCHAR,
    cancel_reason VARCHAR,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 17. background_jobs
CREATE TABLE IF NOT EXISTS public.background_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_type VARCHAR,
    target_type VARCHAR,
    target_id UUID,
    payload JSONB,
    status VARCHAR,
    attempts INTEGER NOT NULL DEFAULT 0,
    error_message TEXT,
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 18. search_vector_configs
CREATE TABLE IF NOT EXISTS public.search_vector_configs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chunk_size INTEGER,
    overlap INTEGER,
    strategy VARCHAR,
    embedding_model VARCHAR,
    vector_dimensions INTEGER,
    is_active BOOLEAN,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 19. search_document_chunks
CREATE TABLE IF NOT EXISTS public.search_document_chunks (
    id UUID PRIMARY KEY,
    digital_copy_id UUID NOT NULL REFERENCES public.digital_copies(id),
    document_id UUID NOT NULL REFERENCES public.documents(id),
    search_config_id BIGINT REFERENCES public.search_vector_configs(id),
    chunk_index INTEGER,
    chapter VARCHAR,
    section VARCHAR,
    page_number INTEGER,
    page_end INTEGER,
    printed_page_label VARCHAR,
    chunk_text TEXT,
    token_count INTEGER,
    embedding vector,
    fts_tokens tsvector,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 20. document_embeddings
CREATE TABLE IF NOT EXISTS public.document_embeddings (
    document_id UUID PRIMARY KEY REFERENCES public.documents(id),
    embedding vector,
    model_version VARCHAR,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 21. document_similarities
CREATE TABLE IF NOT EXISTS public.document_similarities (
    document_a_id UUID NOT NULL REFERENCES public.documents(id),
    document_b_id UUID NOT NULL REFERENCES public.documents(id),
    model_version VARCHAR NOT NULL,
    sim_score DOUBLE PRECISION,
    source VARCHAR,
    PRIMARY KEY (document_a_id, document_b_id, model_version)
);

-- 22. rec_algorithm_registry
CREATE TABLE IF NOT EXISTS public.rec_algorithm_registry (
    rec_model_version VARCHAR PRIMARY KEY,
    algorithm_type VARCHAR,
    is_active BOOLEAN
);

-- 23. recommendations_cache
CREATE TABLE IF NOT EXISTS public.recommendations_cache (
    user_id UUID NOT NULL REFERENCES public.users(id),
    document_id UUID NOT NULL REFERENCES public.documents(id),
    rec_model_version VARCHAR NOT NULL REFERENCES public.rec_algorithm_registry(rec_model_version),
    score DOUBLE PRECISION,
    rank INTEGER,
    reason TEXT,
    generated_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ,
    PRIMARY KEY (user_id, document_id, rec_model_version)
);

-- 24. acquisition_suggestions
CREATE TABLE IF NOT EXISTS public.acquisition_suggestions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT NOT NULL REFERENCES public.departments(id),
    topic VARCHAR,
    source_query_cluster JSONB,
    query_count INTEGER,
    status VARCHAR,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 25. message_queue
CREATE TABLE IF NOT EXISTS public.message_queue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.users(id),
    circulation_id BIGINT REFERENCES public.circulation(id),
    hold_id BIGINT REFERENCES public.holds_queue(id),
    channel VARCHAR,
    message_type VARCHAR,
    content TEXT,
    scheduled_at TIMESTAMPTZ,
    sent_at TIMESTAMPTZ,
    retry_count INTEGER NOT NULL DEFAULT 0,
    error_message TEXT,
    status VARCHAR,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
